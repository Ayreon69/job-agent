"""Schema and access helpers for the job store: Postgres (Neon in production).

The connection string comes from DATABASE_URL (.env locally, a secret in
GitHub Actions and on the deployed API). Until session 20 the store was a
SQLite file committed back to git by the CI bot after every stage: the repo
grew with every run, verdicts set on the deployed dashboard were lost with
the container's copy of the file, and the analyses never left the runner.
"""

from __future__ import annotations

import os
import re
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import date
from typing import Iterator

import psycopg
from dotenv import load_dotenv
from psycopg.types.json import Jsonb

load_dotenv()

# Statuts possibles de jobs.status, gérés par l'orchestrateur (session 5) :
#   nouveau                 - pas encore traité
#   analyse                 - scoring + génération réussis
#   a_valider_geographie    - traité avec succès mais zone géographique
#                              "inconnu" (session 3) : ne pas faire confiance
#                              silencieusement au ton généré, valider à la main
#   echec                   - une étape a levé une exception ; voir la trace
#                              orchestrateur pour le détail
JOB_STATUSES = ("nouveau", "analyse", "a_valider_geographie", "echec")

# Verdict manuel de l'utilisateur (dashboard, tri façon swipe) — indépendant
# du score/statut calculés par le pipeline : c'est un jugement humain, jamais
# recalculé ni influencé par l'agent. NULL = pas encore trié.
USER_VERDICTS = ("interessante", "peut_etre", "pas_interessante")


def _sql_values(values: tuple[str, ...]) -> str:
    return ", ".join(f"'{v}'" for v in values)


# jobs : l'offre telle que scrapée, plus le résumé du scoring (score, zone,
# secteur, nombre d'écarts) que le dashboard public affiche.
# analyses : le contenu personnel (points forts, écarts détaillés, analyse
# rédigée, traces des agents), servi par l'API au seul propriétaire.
#
# last_seen_at reste nullable : 16 lignes héritées de SQLite n'en ont pas
# (insérées avant que upsert_job ne le renseigne, session 19), et les juger
# sur scraped_at les ferait supprimer par storage.cleanup — décision laissée
# à l'utilisateur.
SCHEMA = f"""
CREATE TABLE IF NOT EXISTS jobs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source text NOT NULL,
    source_id text NOT NULL,
    url text NOT NULL,
    title text NOT NULL,
    company text,
    location text,
    contract_type text,
    salary text,
    experience text,
    description text,
    published_at text,
    scraped_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz DEFAULT now(),
    status text NOT NULL DEFAULT 'nouveau' CHECK (status IN ({_sql_values(JOB_STATUSES)})),
    user_verdict text CHECK (user_verdict IN ({_sql_values(USER_VERDICTS)})),
    score integer,
    geography_zone text,
    sector text,
    gaps_count integer,
    uncertain_count integer,
    UNIQUE (source, source_id)
);

CREATE TABLE IF NOT EXISTS analyses (
    job_id integer PRIMARY KEY REFERENCES jobs (id) ON DELETE CASCADE,
    matches jsonb NOT NULL DEFAULT '[]',
    gaps jsonb NOT NULL DEFAULT '[]',
    uncertain_flags jsonb NOT NULL DEFAULT '[]',
    analysis_markdown text,
    orchestrator_trace jsonb,
    scoring_trace jsonb,
    generation_trace jsonb,
    updated_at timestamptz NOT NULL DEFAULT now()
);
"""


@dataclass
class Job:
    source: str
    source_id: str
    url: str
    title: str
    company: str | None = None
    location: str | None = None
    contract_type: str | None = None
    salary: str | None = None
    experience: str | None = None
    description: str | None = None
    published_at: str | None = None


def database_url() -> str:
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise RuntimeError("DATABASE_URL n'est pas défini : mettre la chaîne de connexion Neon dans .env (voir .env.example).")
    return url


@contextmanager
def connect(dsn: str | None = None) -> Iterator[psycopg.Connection]:
    """One transaction: committed when the block exits normally, rolled back
    if it raises. Keep blocks short — the database is remote, and a
    transaction held open across minutes of scraping is lost entirely if the
    connection drops.

    prepare_threshold=None: no server-side prepared statements. They live on
    one server connection, which a transaction-mode pooler (Neon's -pooler
    endpoint) doesn't guarantee from one transaction to the next.
    """
    with psycopg.connect(dsn or database_url(), prepare_threshold=None, connect_timeout=15) as conn:
        yield conn


def init_db(dsn: str | None = None) -> None:
    with connect(dsn) as conn:
        conn.execute(SCHEMA)


def upsert_job(conn: psycopg.Connection, job: Job) -> bool:
    """Insert a job, or — if (source, source_id) already exists — refresh
    the existing row with this run's freshly-scraped values plus
    last_seen_at. The scrapers re-fetch an offer's detail page on every run;
    keeping only the first copy is how published_at used to go stale (a
    source can republish an active listing with a new date, ROADMAP.md
    session 14).

    status, user_verdict, scraped_at (first seen) and the scoring summary
    are never touched: they're this app's own judgment or history, not
    scraped data.

    Returns True if a new row was inserted, False if an existing one was
    refreshed. `xmax = 0` tells the two apart: xmax is the id of the
    transaction that last locked or updated a row version, so it is 0 only
    on a version this INSERT just created, not on one ON CONFLICT updated.
    """
    row = conn.execute(
        """
        INSERT INTO jobs
            (source, source_id, url, title, company, location,
             contract_type, salary, experience, description, published_at)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (source, source_id) DO UPDATE SET
            url = EXCLUDED.url, title = EXCLUDED.title, company = EXCLUDED.company,
            location = EXCLUDED.location, contract_type = EXCLUDED.contract_type,
            salary = EXCLUDED.salary, experience = EXCLUDED.experience,
            description = EXCLUDED.description, published_at = EXCLUDED.published_at,
            last_seen_at = now()
        RETURNING (xmax = 0)
        """,
        (
            job.source,
            job.source_id,
            job.url,
            job.title,
            job.company,
            job.location,
            job.contract_type,
            job.salary,
            job.experience,
            job.description,
            job.published_at,
        ),
    ).fetchone()
    return row[0]


def refresh_job(conn: psycopg.Connection, job_id: int, job: Job) -> None:
    """Overwrite row job_id's scraped fields with this run's values and
    refresh last_seen_at — used to re-point a known offer to the new
    source_id a source republished it under (jobup.ch, see
    scraper/jobup.py's is_same_offer), hence source_id and url being part
    of the refresh. Leaves alone what upsert_job leaves alone.
    """
    conn.execute(
        """
        UPDATE jobs SET
            source_id = %s, url = %s, title = %s, company = %s, location = %s,
            contract_type = %s, salary = %s, experience = %s,
            description = %s, published_at = %s, last_seen_at = now()
        WHERE id = %s
        """,
        (
            job.source_id,
            job.url,
            job.title,
            job.company,
            job.location,
            job.contract_type,
            job.salary,
            job.experience,
            job.description,
            job.published_at,
            job_id,
        ),
    )


def mark_seen(conn: psycopg.Connection, job_ids: list[int]) -> None:
    """Refresh last_seen_at only: these offers showed up again in a search,
    but their detail pages weren't re-fetched (LinkedIn, to keep the request
    volume low — see scraper/linkedin.py). Stored fields stay as first
    fetched. One statement for the whole list (`= ANY` takes a Python list
    as a Postgres array) rather than one round trip per offer."""
    conn.execute("UPDATE jobs SET last_seen_at = now() WHERE id = ANY(%s)", (job_ids,))


def set_job_status(conn: psycopg.Connection, job_id: int, status: str) -> None:
    if status not in JOB_STATUSES:
        raise ValueError(f"Unknown job status {status!r}, expected one of {JOB_STATUSES}")
    conn.execute("UPDATE jobs SET status = %s WHERE id = %s", (status, job_id))


def set_user_verdict(conn: psycopg.Connection, job_id: int, verdict: str | None) -> None:
    """Set (or clear, with verdict=None) the user's own manual triage
    decision for an offer — never touched by the scoring/generation
    pipeline, purely a human judgment recorded from the dashboard.
    """
    if verdict is not None and verdict not in USER_VERDICTS:
        raise ValueError(f"Unknown user verdict {verdict!r}, expected one of {USER_VERDICTS} or None")
    conn.execute("UPDATE jobs SET user_verdict = %s WHERE id = %s", (verdict, job_id))


def set_scoring_summary(
    conn: psycopg.Connection,
    job_id: int,
    *,
    score: int,
    geography_zone: str,
    sector: str | None,
    gaps_count: int,
    uncertain_count: int,
) -> None:
    conn.execute(
        "UPDATE jobs SET score = %s, geography_zone = %s, sector = %s, gaps_count = %s, uncertain_count = %s "
        "WHERE id = %s",
        (score, geography_zone, sector, gaps_count, uncertain_count, job_id),
    )


def _jsonb(value: dict | list | None) -> Jsonb | None:
    # Jsonb(None) would store the JSON value null, not SQL NULL.
    return Jsonb(value) if value is not None else None


def save_analysis(
    conn: psycopg.Connection,
    job_id: int,
    *,
    matches: list[dict],
    gaps: list[dict],
    uncertain_flags: list[str],
    analysis_markdown: str | None,
    orchestrator_trace: dict,
    scoring_trace: dict | None,
    generation_trace: dict | None,
) -> None:
    """Store the latest pipeline run's output for job_id, replacing the
    previous one: the row always describes the run that set jobs.status."""
    conn.execute(
        """
        INSERT INTO analyses
            (job_id, matches, gaps, uncertain_flags, analysis_markdown,
             orchestrator_trace, scoring_trace, generation_trace)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (job_id) DO UPDATE SET
            matches = EXCLUDED.matches, gaps = EXCLUDED.gaps,
            uncertain_flags = EXCLUDED.uncertain_flags,
            analysis_markdown = EXCLUDED.analysis_markdown,
            orchestrator_trace = EXCLUDED.orchestrator_trace,
            scoring_trace = EXCLUDED.scoring_trace,
            generation_trace = EXCLUDED.generation_trace,
            updated_at = now()
        """,
        (
            job_id,
            Jsonb(matches),
            Jsonb(gaps),
            Jsonb(uncertain_flags),
            analysis_markdown,
            Jsonb(orchestrator_trace),
            _jsonb(scoring_trace),
            _jsonb(generation_trace),
        ),
    )


# jobs.published_at is stored verbatim, in whichever format the source site
# used at scrape time (see scraper/hellowork.py and scraper/jobup.py) — NOT
# normalized at scrape time. Two formats exist in practice: Hellowork's
# "DD/MM/YYYY" and jobup.ch's French "DD mois AAAA" (session 11). Shared by
# api/main.py (sort by date) and storage/cleanup.py.
_MOIS_FR = {
    "janvier": 1, "février": 2, "fevrier": 2, "mars": 3, "avril": 4, "mai": 5,
    "juin": 6, "juillet": 7, "août": 8, "aout": 8, "septembre": 9,
    "octobre": 10, "novembre": 11, "décembre": 12, "decembre": 12,
}
_PUBLISHED_AT_SLASH_RE = re.compile(r"^(\d{1,2})/(\d{1,2})/(\d{4})$")
_PUBLISHED_AT_FR_RE = re.compile(r"^(\d{1,2})\s+([a-zéû]+)\s+(\d{4})$", re.IGNORECASE)


def parse_published_at(raw: str | None) -> date | None:
    """Parse jobs.published_at's raw, source-specific text into a real date,
    or None if it's missing or in an unrecognized format.
    """
    if not raw:
        return None
    raw = raw.strip()

    slash_match = _PUBLISHED_AT_SLASH_RE.match(raw)
    if slash_match:
        day, month, year = (int(g) for g in slash_match.groups())
        try:
            return date(year, month, day)
        except ValueError:
            return None

    fr_match = _PUBLISHED_AT_FR_RE.match(raw)
    if fr_match:
        day_str, month_name, year_str = fr_match.groups()
        month = _MOIS_FR.get(month_name.lower())
        if month is None:
            return None
        try:
            return date(int(year_str), month, int(day_str))
        except ValueError:
            return None

    return None
